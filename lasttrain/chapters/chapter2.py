def apply(s,effect):
    if not effect.startswith('c2_'):return False
    if effect=='c2_travel':s.chapter=2
    elif effect=='c2_arrived':s.enter('hospital');s.health=100;s.flares=3
    elif effect in ('c2_admit','c2_defend'):
        s.flags.add('c2_truth');s.choices['hospital_truth']='admit' if effect=='c2_admit' else 'defend'
    elif effect=='c2_boarded':s.enter('carriage')
    return True

def objective(s):
    if s.chapter!=2:return None
    f=s.flags
    if 'c2_complete' in f:return 'Проверить путь к Рабочему посёлку'
    if 'c2_truth' in f:return 'Проверить схему линии в вагоне'
    if 'c2_boarded' in f:return 'Поговорить с Ниной в вагоне'
    if 'action_mode' in f and 'c2_gate_open' not in f and s.winch['stage'] in ('turn','lock'):
        return 'Зафиксировать замок стрелки' if s.winch['stage']=='lock' else 'Перевести стрелку лебёдкой • E на светлой метке'
    if 'c2_gate_open' in f:
        if 'c2_receiving_ready' not in f:return 'Проверить приём пассажиров с Ниной в вагоне'
        if 'c2_pack_ready' not in f:return 'Подготовить с Лидой медицинскую сумку в убежище'
        return 'Вернуться в убежище к Лиде'
    if 'c2_power_ready' in f:return 'Перевести привод стрелки на платформе'
    if 'c2_intro' not in f:return 'Поговорить с Ниной у поезда'
    if 'c2_refuge' not in f:return 'Проверить убежище'
    if 'c2_cable' in f:return 'Соединить обе ветви в распределительной или использовать лебёдку'
    if 'c2_winch' in f:return 'Установить лебёдку у стрелки или восстановить питание'
    return 'Осмотреть схему питания; найти кабель или лебёдку на складе'

def interact(s,key):
    if s.chapter!=2:return None
    f=s.flags;scene=s.scene
    def talk(name):s.start_dialogue(name);return True
    if scene=='carriage':
        if 'c2_complete' in f and key in ('map','cabin'):return talk('c3_departure')
        if 'c2_arrived' not in f:return talk('c2_departure') if key in ('map','cabin') else True
        if 'c2_boarded' not in f:
            if key=='cabin':s.enter('hospital',(550,780));return True
            if key=='nina':return talk('c2_receiving_done' if 'c2_receiving_ready' in f else 'c2_receiving')
            if key=='patient':return talk('c2_waiting_mikhail')
            s.say('Лида ждёт в убежище. Проверьте приём с Ниной, затем выйдите через кабину.');return True
        if key=='nina':return talk('c2_nina_ready' if 'c2_truth' in f else 'c2_truth')
        if key=='lida':return talk('c2_lida_after')
        if key=='patient':return talk('c2_patient_after')
        if key=='map':
            if 'c2_truth' in f:return talk('c2_map')
            s.say('Сначала поговорите с Ниной.');return True
        s.say('Перед отправлением нужно проверить схему.');return True
    if scene=='hospital':
        if key=='nina':return talk('c2_intro')
        if key=='refuge':s.enter('refuge');return True
        if key=='power':s.enter('power');return True
        if key=='yard':s.enter('yard');return True
        if key=='train':
            if 'c2_boarded' in f or 'c2_refuge' in f:s.enter('carriage')
            else:s.say('Сначала узнайте у Лиды в убежище, кого и как принимать в вагон.')
            return True
        if key=='schedule':return talk('c2_plan')
        if key=='switch':
            if 'c2_gate_open' in f:s.say('Стрелка зафиксирована.')
            elif 'c2_refuge' not in f:s.say('Сначала проверьте, кому нужен свет в убежище.')
            elif 'c2_power_ready' in f:
                s.choices['power_route']='electric';return talk('c2_gate_electric')
            elif 'c2_winch' in f:
                s.puzzle='winch';return 'winch'
            else:s.say('Нужны питание привода или ручная лебёдка со склада.')
            return True
    if scene=='refuge':
        if key=='exit':s.enter('hospital',(1250,480));return True
        if key=='lida':
            if 'c2_refuge' not in f:return talk('c2_refuge')
            if 'c2_gate_open' in f:
                if 'c2_receiving_ready' not in f:return talk('c2_need_receiving')
                if 'c2_pack_ready' not in f:return talk('c2_need_pack')
                return talk('c2_boarding_named' if 'c2_card_written' in f else 'c2_boarding')
            return talk('c2_refuge_reminder')
        if key=='roster':return talk('c2_current_card' if 'c2_address' in f and 'c2_card_written' not in f else 'c2_roster')
        if key in ('beds','raisa'):return talk('c2_card_thanks' if 'c2_card_written' in f else 'c2_beds')
        if key=='supplies':
            s.health=100
            if 'c2_refuge' not in f:s.say('Сначала спросите Лиду, что приготовить к выходу.');return True
            if 'c2_pack_ready' not in f:return talk('c2_pack')
            s.say('Сумка проверена и стоит у выхода. До ухода она остаётся рядом с Лидой.');return True
    if scene=='power':
        if key=='exit':s.enter('hospital',(1220,980));return True
        if key=='plan':return talk('c2_plan')
        if key=='generator':return talk('c2_generator')
        if key=='board':
            if 'c2_power_ready' in f or 'c2_gate_open' in f:
                s.say('Путь уже подготовлен. Генератор продолжает питать убежище.');return True
            s.puzzle='power';s.say('Схема отключена от нагрузки. Проверьте обе ветви, прежде чем переключать.');return 'power'
    if scene=='yard':
        if key=='exit':s.enter('hospital',(1400,1130));return True
        if key=='shed':s.enter('shed');return True
        if key=='bell':s.say('Колокол уводит Путевого к левой стене.');return 'bell'
        if key=='bracket':return talk('c2_bracket')
        if key=='memorial':return talk('c2_memorial')
    if scene=='shed':
        if key=='exit':s.enter('yard',(1470,700));return True
        if key=='cable':
            if 'c2_cable' in f:s.say('Перемычка уже взята.');return True
            return talk('c2_cable')
        if key=='winch':
            if 'c2_winch' in f:s.say('Лебёдку уже подготовили для ручного перевода.');return True
            return talk('c2_winch')
        if key=='logbook':return talk('c2_logbook')
    return True

def test_power(s):
    passed,message=PowerBoard.result(s.power,'c2_cable' in s.flags)
    s.say(message)
    if passed:
        s.flags.add('c2_power_ready');s.puzzle=None
    return passed

def operate_winch(s,action):
    message,done=Winch.act(s.winch,action);s.say(message)
    if done:
        s.choices['power_route']='manual';s.puzzle=None;s.start_dialogue('c2_gate_manual')
    return done
