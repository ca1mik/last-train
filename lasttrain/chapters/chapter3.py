def apply(s,effect):
    if not effect.startswith('c3_'):return False
    if effect=='c3_travel':s.chapter=3
    elif effect=='c3_arrived':s.enter('settlement');s.health=100;s.flares=3
    elif effect in ('c3_listen','c3_accuse'):
        s.flags.add('c3_met');s.choices['pavel_response']='listen' if effect=='c3_listen' else 'accuse'
    elif effect=='c3_boarded':s.enter('carriage')
    elif effect in ('c3_letter_early','c3_letter_middle','c3_letter_late'):
        s.flags.add('c3_letters')
        count=sum(flag in s.flags for flag in ('c3_letter_early','c3_letter_middle','c3_letter_late'))
        s.say('Все три черновика прочитаны. Можно обсудить их с Павлом.' if count==3 else f'Прочитано черновиков: {count} из 3. Остальные остаются на столе.')
    elif effect in ('c3_statement_taken','c3_statement_left'):
        s.flags.add('c3_letters_discussed')
        s.choices['pavel_statement']='take' if effect=='c3_statement_taken' else 'leave'
    elif effect in ('c3_share','c3_hold'):
        s.choices['recording_policy']='share' if effect=='c3_share' else 'hold'
        s.flags.add('c3_tape_decided')
    return True

def objective(s):
    if s.chapter!=3:return None
    f=s.flags
    if 'c3_complete' in f:return 'Подготовить путь к диспетчерской'
    if 'c3_nina_after' in f:return 'Обсудить маршрут за столом в вагоне'
    if 'c3_tape_decided' in f:return 'Поговорить с Ниной после решения о записи'
    if 'c3_boarded' in f:return 'Решить, когда пассажиры услышат оригинал записи'
    if 'c3_contact' in f and 'c3_original' in f:return 'Вернуться к Павлу и пригласить его в поезд'
    if 'c3_contact' in f:return 'Забрать оригинал кассеты у Павла'
    if 'c3_repair' in f and not s.line_power:return 'Вернуть питание разъединителем во дворе'
    if 'c3_repair' in f:return 'Настроить приёмник и проверить живой ответ диспетчера'
    if 'c3_spare' in f:return 'Обесточить линию и заменить ввод на настиле'
    if 'c3_met' in f:return 'Осмотреть пост связи и найти запасной изолятор'
    return 'Найти Павла в квартире у станции'

def interact(s,key):
    if s.chapter!=3:return None
    f=s.flags;scene=s.scene
    def talk(name):s.start_dialogue(name);return True
    if scene=='carriage':
        if 'c3_arrived' not in f:return talk('c3_departure') if key in ('map','cabin') else True
        if key=='nina':
            if 'c3_tape_decided' not in f:return talk('c3_tape_decision')
            return talk('c3_nina_shared' if s.choices.get('recording_policy')=='share' else 'c3_nina_held')
        if key=='pavel':return talk('c3_pavel_shared' if s.choices.get('recording_policy')=='share' else 'c3_pavel_held')
        if key=='lida':return talk('c3_lida_after' if s.choices.get('recording_policy')=='share' else 'c3_lida_wait')
        if key=='patient':return talk('c3_patient_after')
        if key=='map':
            if 'c3_tape_decided' not in f:return talk('c3_tape_decision')
            if 'c3_nina_after' in f:return talk('c3_map')
            s.say('Нина хочет поговорить о записи.');return True
        s.say('Перед отправлением обсудите маршрут за столом.');return True
    if scene=='settlement':
        if key=='nina':return talk('c3_nina_open' if s.choices.get('hospital_truth')=='admit' else 'c3_nina_guarded')
        if key=='flat':s.enter('flat');return True
        if key=='relay':s.enter('relay_house');return True
        if key=='yard':s.enter('switchyard');return True
        if key=='notice':return talk('c3_notice')
        if key=='train':s.say('Без живой связи и Павла пока не уезжаем.');return True
    if scene=='flat':
        if key=='exit':s.enter('settlement',(1040,520));return True
        if key=='pavel':
            if 'c3_met' not in f:return talk('c3_pavel_intro')
            if {'c3_letter_early','c3_letter_middle','c3_letter_late'}<=f and 'c3_letters_discussed' not in f:return talk('c3_letters_talk')
            if 'c3_contact' in f and 'c3_original' in f:return talk('c3_pavel_boarding_statement' if s.choices.get('pavel_statement')=='take' else 'c3_pavel_boarding')
            return talk('c3_pavel_work_wary' if s.choices.get('pavel_response')=='accuse' else 'c3_pavel_work')
        if key=='cassette':
            if 'c3_met' in f:return talk('c3_cassette')
            s.say('Не стоит трогать коробку, не поговорив с хозяином.');return True
        if key=='letters' and 'c3_met' not in f:
            s.say('Сначала поговорите с хозяином квартиры.');return True
        if key in ('letters','tools'):return talk('c3_'+key)
    if scene=='relay_house':
        if key=='exit':s.enter('settlement',(1390,1090));return True
        if key=='spare':return talk('c3_spare')
        if key in ('maintenance','recorder'):return talk('c3_'+key)
        if key=='receiver':
            if 'c3_contact' in f:return talk('c3_playback')
            s.puzzle='radio';s.say('Найдите пик приёма. Подайте два или три импульса и проверьте ответ.');return 'radio'
    if scene=='switchyard':
        if key=='exit':s.enter('settlement',(1640,620));return True
        if key=='gantry':s.enter('gantry');return True
        if key=='breaker':
            s.line_power=not s.line_power
            if 'c3_contact' not in f:s.signal_pattern=0
            s.say('Питание линии восстановлено.' if s.line_power else 'Линия обесточена. Можно осмотреть ввод.')
            return True
        if key=='bell':s.say('Колокол уводит Путевых от прохода к настилу.');return 'bell'
        if key=='testpost':return talk('c3_testpost')
    if scene=='gantry':
        if key=='exit':s.enter('switchyard',(1410,520));return True
        if key=='handprint':return talk('c3_handprint')
        if key=='fault':
            if 'c3_repair' in f:s.say('Ввод закреплён. Проверьте питание и вернитесь к приёмнику.')
            elif s.line_power:s.say('На линии есть питание. Сначала отключите разъединитель во дворе.')
            elif 'c3_spare' not in f:s.say('Керамика расколота. Запасной изолятор должен быть на посту связи.')
            else:s.flags.add('c3_repair');s.say('Новый изолятор встал на место. Можно вернуть питание.')
            return True
    return True

def listen(s):
    if 'c3_repair' not in s.flags:
        s.say('Только треск. Повреждён ввод на настиле.');return False
    if not s.line_power:
        s.say('Линия обесточена. Верните питание разъединителем.');return False
    if not RadioTune.locked(s.radio):
        s.say('Слышны обрывки старых переговоров. Ищите чистый пик приёма, а не самый громкий шум.');return False
    if s.signal_pattern not in (2,3):
        s.say('Сигнал чистый. Подайте выбранное число импульсов, чтобы проверить живой ответ.');return False
    s.puzzle=None;s.start_dialogue('c3_contact_'+str(s.signal_pattern));return True

def beacon(s,count):
    if count not in (2,3):return False
    if 'c3_repair' not in s.flags or not s.line_power:
        s.signal_pattern=0;s.say('Линия не готова. Проверочный сигнал не ушёл.');return False
    s.signal_pattern=count;s.say(f'Подано импульсов: {count}. Проверьте ответ в приёмнике.');return True
