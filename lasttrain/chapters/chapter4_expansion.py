def install_endings(dialogues):
    for name in ('c5_testimony','c5_unfinished','c5_testimony_pavel','c5_unfinished_pavel'):
        data=dict(dialogues[name]);data['lines']=list(data['lines'])
        data['lines'].insert(1,('','Дежурная отмечает отдельное примечание Валентины: подпись, сегодняшняя дата, сведения о передаче смены и опись оставшихся дел. Старую страницу журнала не заменяют.'))
        dialogues[name+'_addendum']=data
